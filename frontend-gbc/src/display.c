static uint8_t g_row_tiles[SCREEN_ROWS][SCREEN_COLS];
static uint8_t g_row_pal[SCREEN_ROWS];
static uint8_t g_row_valid[SCREEN_ROWS];

void display_init(void)
{
    uint8_t tile_2bpp[16];
    DISPLAY_OFF;

    if (_cpu == CGB_TYPE) {
        cpu_fast();
    }

    for (uint8_t idx = 0; idx < 96U; idx++) {
        const uint8_t *src = &font_1bpp[(uint16_t)idx * 8U];
        for (uint8_t row = 0; row < 8U; row++) {
            tile_2bpp[row * 2U]      = src[row];
            tile_2bpp[row * 2U + 1U] = src[row];
        }
        set_bkg_data(idx, 1U, tile_2bpp);
    }

    if (_cpu == CGB_TYPE) {
        set_bkg_palette(0U, 6U, bg_palettes);
    } else {
        BGP_REG = DMG_PALETTE(DMG_WHITE, DMG_LITE_GRAY, DMG_DARK_GRAY, DMG_BLACK);
    }

    memset(g_row_valid, 0, sizeof(g_row_valid));
    move_bkg(0U, 0U);
    display_clear(PAL_BODY);
    SHOW_BKG;
    DISPLAY_ON;
}

void display_draw_row(uint8_t y, const char *text, uint8_t pal)
{
    uint8_t tiles[SCREEN_COLS];
    uint8_t attrs[SCREEN_COLS];
    uint8_t reached_end = 0;
    uint8_t attr_val = pal & 0x07U;

    if (y >= SCREEN_ROWS) return;

    for (uint8_t x = 0; x < SCREEN_COLS; x++) {
        uint8_t ch = 0x20U;
        if (!reached_end && text) {
            uint8_t c = (uint8_t)text[x];
            if (c == 0U) {
                reached_end = 1U;
            } else if (c >= 0x20U && c <= 0x7FU) {
                ch = c;
            } else {
                ch = (uint8_t)'?';
            }
        }
        tiles[x] = (uint8_t)(ch - 0x20U);
        attrs[x] = attr_val;
    }

    if (g_row_valid[y] && g_row_pal[y] == attr_val &&
        memcmp(g_row_tiles[y], tiles, SCREEN_COLS) == 0) {
        return;
    }

    memcpy(g_row_tiles[y], tiles, SCREEN_COLS);
    g_row_pal[y]   = attr_val;
    g_row_valid[y] = 1U;

    VBK_REG = VBK_TILES;
    set_bkg_tiles(0U, y, SCREEN_COLS, 1U, tiles);
    if (_cpu == CGB_TYPE) {
        VBK_REG = VBK_ATTRIBUTES;
        set_bkg_tiles(0U, y, SCREEN_COLS, 1U, attrs);
        VBK_REG = VBK_TILES;
    }
}

void display_clear_rows(uint8_t y_start, uint8_t y_end, uint8_t pal)
{
    for (uint8_t y = y_start; y <= y_end && y < SCREEN_ROWS; y++) {
        display_draw_row(y, "", pal);
    }
}

void display_clear(uint8_t pal)
{
    display_clear_rows(0U, SCREEN_ROWS - 1U, pal);
}

void display_draw_header(const char *title, uint8_t is_dirty)
{
    char line[21];
    str_clear(line);
    str_append_char(line, sizeof(line), ' ');
    str_append(line, sizeof(line), title);
    if (is_dirty) {
        str_append(line, sizeof(line), " *");
    }
    display_draw_row(0U, line, PAL_HEADER);
}

void display_draw_subheader(const char *text)
{
    display_draw_row(1U, text, PAL_SUBHDR);
}

void display_draw_footer(const char *hint)
{
    display_draw_row(17U, hint, PAL_SUBHDR);
}

void str_clear(char *dst)
{
    dst[0] = '\0';
}

void str_append(char *dst, uint8_t max_len, const char *src)
{
    uint8_t len = 0;
    if (!dst || !src || max_len == 0U) return;
    while (len + 1U < max_len && dst[len] != '\0') {
        len++;
    }
    while (len + 1U < max_len && *src != '\0') {
        dst[len++] = *src++;
    }
    dst[len] = '\0';
}

void str_append_char(char *dst, uint8_t max_len, char c)
{
    uint8_t len = 0;
    if (!dst || max_len == 0U) return;
    while (len + 1U < max_len && dst[len] != '\0') {
        len++;
    }
    if (len + 1U < max_len) {
        dst[len++] = c;
        dst[len] = '\0';
    }
}

void str_append_u32(char *dst, uint8_t max_len, uint32_t val)
{
    char tmp[11];
    uint8_t pos = 0;
    if (val == 0U) {
        str_append_char(dst, max_len, '0');
        return;
    }
    while (val > 0U && pos < sizeof(tmp)) {
        tmp[pos++] = (char)('0' + (uint8_t)(val % 10U));
        val /= 10U;
    }
    while (pos > 0U) {
        pos--;
        str_append_char(dst, max_len, tmp[pos]);
    }
}

void str_append_u16_pad(char *dst, uint8_t max_len, uint16_t val,
                        uint8_t width, char pad)
{
    char tmp[6];
    uint8_t pos = 0;
    if (val == 0U) {
        tmp[pos++] = '0';
    } else {
        while (val > 0U && pos < sizeof(tmp)) {
            tmp[pos++] = (char)('0' + (uint8_t)(val % 10U));
            val /= 10U;
        }
    }
    while (pos < width) {
        str_append_char(dst, max_len, pad);
        width--;
    }
    while (pos > 0U) {
        pos--;
        str_append_char(dst, max_len, tmp[pos]);
    }
}
