"""
Generate `species_sprite_lookup.cpp` for the pokemon editor's right panel.

Background: see docs/frontend-gba-plan.md §"Checkpoint #6 — Sprites" follow-up
"Per-species render branch". `tools/extract_sprites.py` (optional, gated on
`make gba SPRITES_ROM=/path/to/gen3.gba`) dumps `species_NNN.bmp` files
into `frontend-gba/graphics/sprites/`. This generator walks that directory
and emits a C++ switch mapping species id → `bn::sprite_item*`. Species
without an extracted BMP fall through to nullptr; the scene picks the
generic silhouette in that case.

Why a switch and not an array: butano's `bn::sprite_item` symbols
are resolved at link time, so the lookup can only reference the
symbols that grit actually produced — which depends on which BMPs the
user supplied. A switch over present-only ids keeps the lookup
self-contained; an array indexed by species_id would need conditional
inclusion or a parallel "is this species available" bitmap.

The generator is deterministic: same inputs always produce byte-identical
output. This matters for incremental builds — `make` only re-runs the
butano translation unit if the .cpp content actually changed.
"""

import argparse
import os
import re
import sys

_SPECIES_PATTERN = re.compile(r"^species_(\d{3})\.bmp$")


def generate(sprites_dir: str, out_path: str) -> int:
    """Walk `sprites_dir` for `species_NNN.bmp` files, emit lookup at `out_path`.

    Returns the number of species cases emitted. Missing directory is
    treated as "no sprites" — the lookup compiles and always returns
    nullptr, so the default `make gba` (no SPRITES_ROM) build still ships.
    """
    species_ids = []
    if os.path.isdir(sprites_dir):
        for name in os.listdir(sprites_dir):
            m = _SPECIES_PATTERN.match(name)
            if m:
                species_ids.append(int(m.group(1)))
    species_ids.sort()

    cpp = _render(species_ids)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(cpp)
    return len(species_ids)


def _render(species_ids) -> str:
    """Render the .cpp body for the sorted `species_ids` (may be empty)."""
    includes = "".join(
        f'#include "bn_sprite_items_species_{sid:03d}.h"\n'
        for sid in species_ids
    )
    cases = "".join(
        f"        case {sid}: return &bn::sprite_items::species_{sid:03d};\n"
        for sid in species_ids
    )
    return (
        "// SPDX-License-Identifier: MIT\n"
        "// Generated by tools/gen_sprite_lookup.py — DO NOT EDIT.\n"
        "//\n"
        "// Maps Pokemon species ids to the bn::sprite_item* produced by\n"
        "// butano's grit from frontend-gba/graphics/sprites/species_NNN.bmp.\n"
        "// Species without an extracted BMP return nullptr; the scene\n"
        "// substitutes the generic silhouette in that case.\n"
        "\n"
        "#include <bn_sprite_item.h>\n"
        f"{includes}"
        "\n"
        "namespace pksave_gba {\n"
        "namespace sprite_lookup {\n"
        "\n"
        "const bn::sprite_item* species_sprite_for(int id)\n"
        "{\n"
        "    switch (id)\n"
        "    {\n"
        f"{cases}"
        "        default: return nullptr;\n"
        "    }\n"
        "}\n"
        "\n"
        "}  // namespace sprite_lookup\n"
        "}  // namespace pksave_gba\n"
    )


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate species_sprite_lookup.cpp for frontend-gba.",
    )
    parser.add_argument(
        "--sprites-dir", required=True,
        help="directory containing species_NNN.bmp files (typ. "
             "frontend-gba/graphics/sprites/)")
    parser.add_argument(
        "--out", required=True,
        help="path to write the generated .cpp")
    args = parser.parse_args(argv)
    n = generate(args.sprites_dir, args.out)
    print(f"gen_sprite_lookup: emitted {n} species cases → {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
